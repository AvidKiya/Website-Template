function buildProduct(seed: Seed, index: number): Product {
  const brand = brands.find((b) => b.slug === seed.brandSlug);
  return {
    id: `p${index + 1}`,
    slug: seed.slug,
    title: seed.title,
    englishTitle: seed.englishTitle,
    categorySlug: seed.categorySlug,
    brandSlug: seed.brandSlug,
    images: seed.imageIds.map((id) => img(id, 1100)),
    price: seed.price,
    oldPrice: seed.oldPrice,
    rating: seed.rating,
    reviewCount: seed.reviewCount,
    stock: seed.stock,
    colors: seed.colors,
    sizes: seed.sizes ?? [],
    seller: {
      name:
        index % 3 === 0
          ? "فروشگاه مرکزی یور برند"
          : index % 3 === 1
            ? "گالری اطلس"
            : "بوتیک پردیس",
      rating: 4.2 + ((index % 7) / 10),
      sales: 1200 + index * 137,
      badge: index % 2 === 0 ? "فروشنده برگزیده" : undefined,
    },
    warranty: "۱۸ ماه ضمانت اصالت و سلامت فیزیکی کالا",
    shipping: seed.stock > 10 ? "ارسال امروز در تهران" : "ارسال ۲ تا ۳ روز کاری",
    description:
      seed.description ??
      `${seed.title} محصولی از برند ${brand?.title ?? ""} است که با تمرکز بر کیفیت ساخت، دوام و راحتی استفاده روزمره طراحی شده است. مواد اولیه با دقت انتخاب شده و کالا پیش از ارسال از نظر سلامت فیزیکی و اصالت بررسی می‌شود. جزئیات پرداخت نهایی، هماهنگی رنگ‌بندی و سادگی طراحی باعث می‌شود این کالا با بیشتر استایل‌های روزمره و رسمی ست شود.`.trim(),
    highlights: [
      "کیفیت دوخت و پرداخت نهایی در سطح بالا",
      "مناسب استفاده روزمره و موقعیت‌های رسمی",
      "امکان بازگشت کالا تا ۷ روز پس از تحویل",
      "بسته‌بندی ایمن و ارسال سریع",
    ],
    specifications: seed.specs ?? [
      { label: "برند", value: `${brand?.title ?? "—"} (${brand?.latin ?? ""})` },
      {
        label: "دسته‌بندی",
        value: categories.find((c) => c.slug === seed.categorySlug)?.title ?? "عمومی",
      },
      { label: "جنس", value: "ترکیب الیاف مرغوب" },
      { label: "کشور سازنده", value: "ایران" },
      { label: "نوع بسته‌بندی", value: "جعبه اختصاصی برند" },
      { label: "شرایط نگهداری", value: "دور از نور مستقیم آفتاب" },
      { label: "وزن تقریبی", value: "۵۰۰ گرم" },
    ],
    tags: seed.tags,
    createdAt: new Date(Date.now() - seed.daysAgo * 86400000).toISOString(),
  };
}

export const products: Product[] = seeds.map(buildProduct);

export const productBySlug = (slug: string) => products.find((p) => p.slug === slug);
